/* Generates pub-realm.css: the pub's authored stylesheets scoped under .pub-realm so the pub
   can live inside the Supreme Command page. Run after editing style.css or pub-annex.css. */
import fs from 'node:fs';
const SCOPE = '.pub-realm';
function scopeSelector(sel) {
  sel = sel.trim();
  if (!sel) return sel;
  if (/^(:root|html|body)$/.test(sel)) return SCOPE;
  if (/^html\s+body$/.test(sel)) return SCOPE;
  // body.fenton-mode .x  ->  body.fenton-mode .pub-realm .x ; body.x -> body.x .pub-realm
  const m = sel.match(/^body((?:\.[\w-]+)*)(\s+.*)?$/);
  if (m) return `body${m[1]} ${SCOPE}${m[2] ? m[2] : ''}`;
  if (sel.startsWith(':root')) return SCOPE + sel.slice(5);
  return `${SCOPE} ${sel}`;
}
function transform(css) {
  let out = '', i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) { out += css.slice(i); break; }
    const prelude = css.slice(i, open);
    const close = matching(css, open);
    const body = css.slice(open + 1, close);
    const comments = prelude.match(/\/\*[\s\S]*?\*\//g) || [];
    // A section comment often sits immediately before an at-rule. Detect the
    // rule after removing comments; otherwise `/* responsive */ @media` is
    // mistaken for a selector and emitted as the invalid `.pub-realm @media`.
    const barePrelude = prelude.replace(/\/\*[\s\S]*?\*\//g, '');
    const head = barePrelude.trim();
    const prefix = comments.join('\n') + (comments.length ? '\n' : '');
    if (head.startsWith('@')) {
      const keepAsIs = /^@(keyframes|font-face|-webkit-keyframes)/.test(head);
      // The scoped pub can be narrower than the viewport because the command
      // sidebar remains beside it. Width media queries must therefore become
      // queries against the .pub-realm container itself.
      const scopedHead = /^@media\s*\(\s*(?:max|min)-width\s*:/.test(head)
        ? head.replace(/^@media/, '@container pub-realm')
        : head;
      out += prefix + scopedHead + ' {' + (keepAsIs ? body : transform(body)) + '}';
    } else {
      const selectors = barePrelude.split(',').map(scopeSelector).join(', ');
      out += prefix + selectors + ' {' + body + '}';
    }
    i = close + 1;
  }
  return out;
}
function matching(css, open) {
  let depth = 0;
  for (let j = open; j < css.length; j++) {
    if (css[j] === '{') depth++;
    else if (css[j] === '}' && --depth === 0) return j;
  }
  throw new Error('Unbalanced CSS');
}
const sources = ['style.css', 'pub-annex.css'];
const output = `/* GENERATED by tools/scope-pub-css.mjs from ${sources.join(' + ')}. Edit those files, then regenerate. */\n` +
  sources.map((f) => `\n/* ---- ${f} ---- */\n` + transform(fs.readFileSync(f, 'utf8'))).join('\n');
fs.writeFileSync('pub-realm.css', output);
console.log(`pub-realm.css written (${output.length} bytes).`);
